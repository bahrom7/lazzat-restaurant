class Command(BaseCommand):
    help = "8 tilda 100+ taom databazaga qo'shadi"

    def handle(self, *args, **kwargs):
        MenuItem.objects.all().delete()
        Category.objects.all().delete()

        total = 0
        for cat_data in DATA:
            cat = Category.objects.create(
                name    = cat_data['name'],
                name_ru = cat_data.get('name_ru', cat_data['name']),
                name_kz = cat_data.get('name_kz', cat_data['name']),
                name_en = cat_data.get('name_en', cat_data['name']),
                name_tr = cat_data.get('name_tr', cat_data['name']),
                name_ar = cat_data.get('name_ar', cat_data['name']),
                name_ko = cat_data.get('name_ko', cat_data['name']),
                name_zh = cat_data.get('name_zh', cat_data['name']),
                icon    = cat_data['icon']
            )
            for row in cat_data['items']:
                (uz_n, uz_d, ru_n, ru_d, kz_n, kz_d,
                 en_n, en_d, tr_n, tr_d, ar_n, ar_d,
                 ko_n, ko_d, zh_n, zh_d, price, photo_id) = row
                url = f"https://images.unsplash.com/{photo_id}?auto=format&fit=crop&w=400&q=80"
                MenuItem.objects.create(
                    category=cat,
                    name=uz_n, name_ru=ru_n, name_kz=kz_n,
                    name_en=en_n, name_tr=tr_n, name_ar=ar_n,
                    name_ko=ko_n, name_zh=zh_n,
                    description=uz_d, description_ru=ru_d, description_kz=kz_d,
                    description_en=en_d, description_tr=tr_d, description_ar=ar_d,
                    description_ko=ko_d, description_zh=zh_d,
                    price=price, image_url=url, is_available=True,
                )
                total += 1

        self.stdout.write(self.style.SUCCESS(
            f"✅ {total} ta taom 8 tilda qo'shildi! "
            f"Kategoriya: {Category.objects.count()}"
        ))
